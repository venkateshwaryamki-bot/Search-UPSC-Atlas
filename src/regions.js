  const by = (fn) => R.filter(fn).map((r) => r.id);
  const borderOf = (c) => by((r) => r.borders.includes(c));
  return [
    { id: "pakistan", group: "Borders", label: "Pakistan", ids: borderOf("Pakistan") },
    { id: "china", group: "Borders", label: "China", ids: borderOf("China") },
    { id: "nepal", group: "Borders", label: "Nepal", ids: borderOf("Nepal") },
    { id: "bhutan", group: "Borders", label: "Bhutan", ids: borderOf("Bhutan") },
    { id: "bangladesh", group: "Borders", label: "Bangladesh", ids: borderOf("Bangladesh") },
    { id: "myanmar", group: "Borders", label: "Myanmar", ids: borderOf("Myanmar") },
    { id: "afghanistan", group: "Borders", label: "Afghanistan", ids: borderOf("Afghanistan") },
    { id: "coastal", group: "Geography", label: "Coastline", ids: by((r) => r.coastal) },
    { id: "landlocked", group: "Geography", label: "No coast or border", ids: by((r) => !r.coastal && r.borders.length === 0) },
    { id: "sched5", group: "Constitution", label: "Fifth Schedule", ids: by((r) => r.schedule === 5) },
    { id: "sched6", group: "Constitution", label: "Sixth Schedule", ids: by((r) => r.schedule === 6) },
    { id: "ut", group: "Constitution", label: "Union Territories", ids: by((r) => r.kind === "UT") },
    { id: "new", group: "Constitution", label: "Formed since 2000", ids: ["ct", "jh", "ut", "tg", "jk", "la", "dh"] },
  ];
